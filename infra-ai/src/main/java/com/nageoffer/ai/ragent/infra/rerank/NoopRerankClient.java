package com.nageoffer.ai.ragent.infra.rerank;

import com.nageoffer.ai.ragent.framework.convention.RetrievedChunk;
import com.nageoffer.ai.ragent.infra.enums.ModelProvider;
import com.nageoffer.ai.ragent.infra.model.ModelTarget;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.stream.Collectors;

@Service
public class NoopRerankClient implements RerankClient {
    // 不调用模型的重排实现。保留原顺序和原分数，必要时只截取前 topN 条，可作为配置中的回退候选，但不产生真实精排分数。

    @Override
    public String provider() {
        // 返回 NOOP 标识，选择器允许该候选没有供应商连接配置。
        return ModelProvider.NOOP.getId();
    }

    @Override
    public List<RetrievedChunk> rerank(String query, List<RetrievedChunk> candidates, int topN, ModelTarget target) {
        // 保留原顺序和原分数，不调用远程模型；topN 无限制或已足够时直接返回原列表，否则只截前 topN 项。
        if (candidates == null || candidates.isEmpty()) {
            return List.of();
        }
        if (topN <= 0 || candidates.size() <= topN) {
            return candidates;
        }
        return candidates.stream()
                .limit(topN)
                .collect(Collectors.toList());
    }
}
